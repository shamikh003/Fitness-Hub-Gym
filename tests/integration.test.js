async function request(route, method='GET', body, auth=false, headers={}) {
 const res = await fetch(base+route,{method,headers:{'Content-Type':'application/json',...(auth?{cookie}:{}),...headers},body:body===undefined?undefined:JSON.stringify(body)});
 const data = await res.json(); return {res,data};
}
